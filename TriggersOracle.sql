-- Triggers
-- 1) Statement.
-- Table qui stocke le nombre total de nageurs.
BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE P17_Statistiques (
        StatID NUMBER PRIMARY KEY,
        NbTotalNageurs NUMBER
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN  -- Ignore l'erreur si la table existe déjà
            RAISE;
        END IF;
END;
/

-- Procedure qui sera appelée par le trigger
CREATE OR REPLACE PROCEDURE P17_Proc_UpdateTotalNageurs
AS
    total_nageurs NUMBER;
BEGIN
    -- Calculer le nombre total de nageurs
    SELECT COUNT(*) INTO total_nageurs FROM P17_Nageurs;

    -- Mettre à jour ou insérer les statistiques
    BEGIN
        UPDATE P17_Statistiques
        SET NbTotalNageurs = total_nageurs
        WHERE StatID = 1;

        IF SQL%ROWCOUNT = 0 THEN
            INSERT INTO P17_Statistiques (StatID, NbTotalNageurs)
            VALUES (1, total_nageurs);
        END IF;
    END;
END;
/

-- Création du trigger
CREATE OR REPLACE TRIGGER P17_Trigger_UpdateTotalNageurs
AFTER INSERT OR DELETE ON P17_Nageurs
BEGIN
    P17_Proc_UpdateTotalNageurs;
END;
/

