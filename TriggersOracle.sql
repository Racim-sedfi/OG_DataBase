-- 2) ROW.
-- table qui sauvegarde l'historique des modifications.
BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE P17_HistoriqueModifications (
        HistoriqueID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        OperationType VARCHAR2(10),
        NageurID NUMBER,
        EpreuveID NUMBER,
        DateModification TIMESTAMP,
        ValeursAnciennes CLOB,
        ValeursNouvelles CLOB
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN  -- Ignore l'erreur si la table existe déjà
            RAISE;
        END IF;
END;
/

-- Création de la procédure pour enregistrer les modifications
CREATE OR REPLACE PROCEDURE P17_Proc_LogModifications(
    operation_type IN VARCHAR2,
    old_values IN OUT CLOB,
    new_values IN OUT CLOB,
    nageur_id IN NUMBER,
    epreuve_id IN NUMBER
)
AS
BEGIN
    INSERT INTO P17_HistoriqueModifications (
        OperationType,
        NageurID,
        EpreuveID,
        DateModification,
        ValeursAnciennes,
        ValeursNouvelles
    )
    VALUES (
        operation_type,
        nageur_id,
        epreuve_id,
        SYSTIMESTAMP,
        old_values,
        new_values
    );
END;
/

-- Création du trigger
CREATE OR REPLACE TRIGGER P17_Trigger_LogModifications
AFTER INSERT OR UPDATE OR DELETE ON P17_ParticiperIndividuel
FOR EACH ROW
DECLARE
    old_values CLOB := NULL;
    new_values CLOB := NULL;
BEGIN
    -- Convertir les anciennes et nouvelles valeurs en JSON
    IF UPDATING OR DELETING THEN
        old_values := JSON_OBJECT(
            'NageurID' VALUE :OLD.NageurID,
            'EpreuveID' VALUE :OLD.EpreuveID,
            'Position' VALUE :OLD.Position,
            'Temps' VALUE :OLD.Temps,
            'Couloir' VALUE :OLD.Couloir,
            'Medaille' VALUE :OLD.Medaille
        );
    END IF;

    IF INSERTING OR UPDATING THEN
        new_values := JSON_OBJECT(
            'NageurID' VALUE :NEW.NageurID,
            'EpreuveID' VALUE :NEW.EpreuveID,
            'Position' VALUE :NEW.Position,
            'Temps' VALUE :NEW.Temps,
            'Couloir' VALUE :NEW.Couloir,
            'Medaille' VALUE :NEW.Medaille
        );
    END IF;

    -- Appel de la procédure pour enregistrer les modifications
    P17_Proc_LogModifications(
        operation_type => CASE
            WHEN INSERTING THEN 'INSERT'
            WHEN UPDATING THEN 'UPDATE'
            WHEN DELETING THEN 'DELETE'
        END,
        old_values => old_values,
        new_values => new_values,
        nageur_id => COALESCE(:OLD.NageurID, :NEW.NageurID),
        epreuve_id => COALESCE(:OLD.EpreuveID, :NEW.EpreuveID)
    );
END;
/

